// 1. React நூலகத்திலிருந்து (Library) நிலையை (State) நிர்வகிப்பதற்குத் தேவையான useState எனும் Hook-ஐ இறக்குமதி (Import) செய்கிறோம்.
import { useState } from 'react';

// 2. Project 3-ற்கான ToggleProject எனும் முதன்மை கூறுச் சார்பை (Component Function) வரையறுக்கிறோம்.
function ToggleProject() {
  
  // 3. isVisible எனும் நிலை மாறியையும் (State Variable) அதை மாற்றியமைக்கக்கூடிய setIsVisible எனும் செயல்பாட்டுச் சார்பையும் (Setter Function) useState மூலமாக உருவாக்குகிறோம்.
  // 4. ஆரம்பத்தில் தகவலை மறைத்து வைக்க வேண்டும் என்பதால், useState-ன் தொடக்க மதிப்பை false என அமைக்கிறோம்.
  const [isVisible, setIsVisible] = useState(false);

  // 5. இந்த கூறு (Component) பயனர் திரையில் எதைத் திரையிட வேண்டும் என்பதற்கான JSX அமைப்பைத் திருப்பி அனுப்புகிறது (Return).
  return (
    // 6. இந்த திட்டப் பிரிவின் உள்ளடக்கங்கள் அனைத்தையும் உள்ளடக்கும் பிரதான கொள்கலன் (Main Container Div).
    // 7. இந்த div-ல் உள்ள அனைத்துப் பொருட்களையும் இடதுபக்கமாகச் சீரமைக்கிறோம் (textAlign: 'left') மற்றும் மேலேயும் கீழேயும் 10px உள் இடைவெளி (padding) தருகிறோம்.
    <div style={{ textAlign: 'left', padding: '10px 0' }}>
      
      {/* 8. தகவலைக் காட்டவும் மறைக்கவும் உதவும் பிரத்யேகமான Toggle பொத்தான் (Button Container). */}
      <button
        // 9. பயனர் இந்தப் பொத்தானைக் கிளிக் செய்யும்போது (onClick Event Trigger ஆகும் போது)...
        // 10. setIsVisible சார்பை அழைத்து, தற்போதைய isVisible மதிப்பை தலைகீழாக மாற்றுமாறு (!isVisible) கட்டளையிடுகிறோம் (true என்றால் false, false என்றால் true என மாறும்).
        onClick={() => setIsVisible(!isVisible)}
        // 11. இந்த பொத்தானுக்கான CSS இன்லைன் வடிவமைப்புப் பண்புகளை (Inline Styles) Styling Object மூலம் வழங்குகிறோம்.
        style={{
          // 12. பொத்தானின் பின்னணி நிறத்தை பிரகாசமான ஆகாய நீல நிறமாக (#38bdf8) அமைக்கிறோம்.
          backgroundColor: '#38bdf8',
          // 13. பொத்தானில் உள்ள எழுத்துக்களின் நிறத்தை அடர் நீலச் சாம்பல் நிறமாக (#0f172a) அமைக்கிறோம்.
          color: '#0f172a',
          // 14. பொத்தானின் உள்புற இடைவெளியை (Padding) மேலேயும் கீழேயும் 10px, இடது மற்றும் வலது புறங்களில் 20px என அமைக்கிறோம்.
          padding: '10px 20px',
          // 15. பொத்தானைச் சுற்றியுள்ள இயல்பான எல்லைக் கோட்டை (Border) நீக்குகிறோம்.
          border: 'none',
          // 16. பொத்தானின் நான்கு மூலைகளையும் 6px அளவிற்கு வளைக்கிறோம் (Border Radius).
          borderRadius: '6px',
          // 17. சுட்டியை (Mouse Cursor) பொத்தானின் மேல் கொண்டு செல்லும் போது, அதைக் கை குறியீடாக (Pointer) மாற்றுகிறோம்.
          cursor: 'pointer',
          // 18. பொத்தானில் உள்ள எழுத்துக்களைத் தடித்த எழுத்துக்களாக (Bold Text) மாற்றுகிறோம்.
          fontWeight: 'bold',
          // 19. பொத்தானுக்குக் கீழே உள்ள தகவல் பெட்டிக்கும் இதற்கும் இடையே 16px வெளி இடைவெளி (Margin Bottom) அளிக்கிறோம்.
          marginBottom: '16px',
          // 20. பொத்தான் எழுத்தின் அளவை (Font Size) 0.95rem ஆக அமைக்கிறோம்.
          fontSize: '0.95rem'
        }}
      >
        {/* 21. JavaScript Ternary Operator (நிபந்தனை இயக்கி) மூலம் பொத்தானின் உரையைத் தீர்மானிக்கிறோம். */}
        {/* 22. isVisible-ன் மதிப்பு true ஆக இருந்தால் 'Hide Content' என்றும், false ஆக இருந்தால் 'Show Content' என்றும் பொத்தானின் உரையைத் திரையிடுகிறோம். */}
        {isVisible ? 'Hide Content' : 'Show Content'}
      </button>

      {/* 23. React Conditional Rendering (நிபந்தனை அடிப்படையிலான திரையிடல்) மற்றும் Short-circuit (&&) இயக்கியைப் பயன்படுத்துகிறோம். */}
      {/* 24. isVisible-ன் மதிப்பு true ஆக இருக்கும் தருணத்தில் மட்டுமே இதற்கு அடுத்துள்ள <div> பகுதி திரையில் தோன்றும் (Render ஆகும்). */}
      {isVisible && (
        // 25. தோன்றும் தகவல் உரையை உள்ளடக்கிய கொள்கலன் (Content Container Div).
        <div style={{
          // 26. தகவல் பெட்டியின் பின்னணி நிறத்தை அடர் நீலச் சாம்பல் நிறமாக (#0f172a) அமைக்கிறோம்.
          backgroundColor: '#0f172a',
          // 27. பெட்டியின் உட்புற இடைவெளியை (Padding) நான்கு பக்கங்களிலும் 16px ஆக அமைக்கிறோம்.
          padding: '16px',
          // 28. தகவல் பெட்டியின் நான்கு மூலைகளையும் 8px அளவிற்கு வளைக்கிறோம் (Border Radius).
          borderRadius: '8px',
          // 29. தகவல் பெட்டியில் உள்ள உரை எழுத்துக்களின் நிறத்தை பளிச்சின வெள்ளை நிறமாக (#f8fafc) அமைக்கிறோம்.
          color: '#f8fafc',
          // 30. தகவல் பெட்டியின் இடதுபக்கத்தில் மட்டும் 4px தடிமனுள்ள பிரகாசமான பச்சை நிறக் கோடு (Border Left) அமைக்கிறோம்.
          borderLeft: '4px solid #10b981',
          // 31. தகவல் உரை எழுத்தின் அளவை (Font Size) 0.95rem ஆக அமைக்கிறோம்.
          fontSize: '0.95rem',
          // 32. வரிகளுக்கு இடையே இருக்கும் இடைவெளியை (Line Height) 1.5 ஆக அமைத்து எளிதாக வாசிக்கும்படி செய்கிறோம்.
          lineHeight: '1.5'
        }}>
          {/* 33. பயனர் காண வேண்டிய முதன்மைத் தகவல் பத்தி (Paragraph Tag). */}
          {/* 34. p Tag-ன் இயல்பான வெளிப்புற இடைவெளியை (Margin) 0 என நீக்குகிறோம். */}
          <p style={{ margin: 0 }}>
            {/* 35. திரையில் தோன்றும் உரை உள்ளடக்கம். */}
            Hello! This content is toggled on and off using React useState hook.
          </p>
        </div>
      )}

    </div>
  );
}

// 36. இந்த ToggleProject Component-ஐ App.jsx போன்ற பிற கோப்புகளில் இறக்குமதி செய்து பயன்படுத்த வசதியாக ஏற்றுமதி (Export Default) செய்கிறோம்.
export default ToggleProject;